%% ==============================================================
% PERIODIC HILL: SPALDING vs ML
% WALL SHEAR STRESS / SKIN FRICTION
%
% Reads wallShearStressMean (the fieldAverage'd field, NOT the instantaneous
% wallShearStress - see system/functions' own comment on why: for LES, a single
% instantaneous snapshot is a chaotic turbulent instant, not the converged mean
% quantity Spalding's law actually describes, so comparing against it isn't a
% fair or meaningful comparison) from the "hills" patch, averaged over
% Hansen/Yang/Abkar's own Tf=200 flow-through-time window (see controlDict/
% system/functions), and compares the signed streamwise/tangential skin-friction
% coefficient.
%
% OpenFOAM wallShearStress dimensions:
%
%       [0 2 -2 0 0 0 0]
%
% Therefore wallShearStress (and its time-average) is kinematic:
%
%       tau_w / rho
%
% With Ub = 1 m/s:
%
%       Cf = 2*tau_w,t
%
% ==============================================================

clear;
clc;
close all;

%% ==============================================================
% CASE SETTINGS
% ==============================================================
% endTime = 2000 (200 flow-through times of averaging + ~22 FTT spin-up, per
% controlDict) - was '0.1'/'0.09', an early, barely-past-the-initial-transient
% instant under the OLD (wrong) endTime=0.5 convention.

cases(1).name  = 'Spalding';
cases(1).dir   = 'spaldingSim';
cases(1).time  = '2000';
cases(1).color = [0.0000 0.4470 0.7410];

cases(2).name  = 'ML';
cases(2).dir   = 'mlSim';
cases(2).time  = '2000';
cases(2).color = [0.8500 0.3250 0.0980];

%% ==============================================================
% FLOW SETTINGS
% ==============================================================

Ub = 1.0;

%% ==============================================================
% MAIN FIGURE
% ==============================================================

figure('Color','w');
hold on;

%% ==============================================================
% PLOT HILL GEOMETRY
% ==============================================================

xhHill = linspace(0,9,1000);

ywHill = arrayfun( ...
    @hillHeight, ...
    xhHill);

% Offset the hill slightly downward so that it does not obscure
% the Cf curve when Cf is close to zero.
plot( ...
    xhHill, ...
    zeros(size(xhHill)), ...
    'k-', ...
    'LineWidth',2.0, ...
    'HandleVisibility','off');

%% ==============================================================
% READ AND PLOT EACH CASE
% ==============================================================

for c = 1:length(cases)

    fprintf('\n');
    fprintf('============================================\n');
    fprintf('Reading %s\n',cases(c).name);
    fprintf('============================================\n');

    %% ----------------------------------------------------------
    % File
    % -----------------------------------------------------------

    file = fullfile( ...
        cases(c).dir, ...
        cases(c).time, ...
        'wallShearStressMean');

    %% ----------------------------------------------------------
    % Read hill wall shear
    % -----------------------------------------------------------

    [tauRaw,~,~] = readWallShearStress(file);

    %% ----------------------------------------------------------
    % Number of wall faces
    % -----------------------------------------------------------

    fprintf( ...
        'Wall shear vectors = %d\n', ...
        size(tauRaw,1));

    %% ----------------------------------------------------------
    % Read wall-face geometry
    %
    % This uses the OpenFOAM patch data generated by the
    % wallShearStress field if available.
    %
    % At this point, we use a uniform x distribution as an
    % initial fallback only.
    % -----------------------------------------------------------

    nFaces = size(tauRaw,1);

    %% ----------------------------------------------------------
    % IMPORTANT:
    %
    % wallShearStress itself does not contain the wall-face
    % coordinates. If your raw wallShearStress data are ordered
    % consistently with the hill patch, x/h can be reconstructed
    % from the 120 x 60 structured patch.
    % -----------------------------------------------------------

    Nx = 120;
    Nz = 60;

    if nFaces ~= Nx*Nz

        error( ...
            ['Expected %d hill faces (=120*60), but found %d ' ...
             'in %s'], ...
            Nx*Nz, ...
            nFaces, ...
            file);

    end

    %% ----------------------------------------------------------
    % Reshape wall shear
    % -----------------------------------------------------------

    tau = reshape( ...
        tauRaw, ...
        [Nx Nz 3]);

    %% ----------------------------------------------------------
    % Build x coordinates of wall faces
    %
    % Your mesh contains 120 cells in x, so face locations are
    % approximately:
    %
    %   x/h = 0, 0.075, ..., 8.925
    %
    % -----------------------------------------------------------

    xFace = ((0:Nx-1) + 0.5)*(9/Nx);

    %% ----------------------------------------------------------
    % Tangential shear
    %
    % Hill tangent:
    %
    %       t = (1,dy/dx)
    %
    % normalized.
    %
    % tau_t = tau_x*t_x + tau_y*t_y
    %
    % -----------------------------------------------------------

    tauTangential = zeros(Nx,1);

    %% ----------------------------------------------------------
    % Spanwise average
    % -----------------------------------------------------------

    for i = 1:Nx

        xh = xFace(i);

        %% Hill derivative

        dx = 1e-5;

        yp = hillHeight(xh + dx);
        ym = hillHeight(xh - dx);

        dydx = (yp - ym)/(2*dx);

        %% Tangent vector

        tx = 1/sqrt(1 + dydx^2);
        ty = dydx/sqrt(1 + dydx^2);

        %% All z faces at this x

        tauX = squeeze(tau(i,:,1));
        tauY = squeeze(tau(i,:,2));

        %% Tangential wall shear

        tauT = tauX*tx + tauY*ty;

        %% Spanwise average

        tauTangential(i) = mean(tauT);

    end

    %% ----------------------------------------------------------
    % Skin friction coefficient
    %
    % OpenFOAM field is tau/rho
    %
    % Cf = (tau/rho)/(0.5 Ub^2)
    % -----------------------------------------------------------

    Cf = tauTangential/(0.5*Ub^2);

    %% ----------------------------------------------------------
    % Store results
    % -----------------------------------------------------------

    cases(c).x = xFace;
    cases(c).Cf = Cf;

    %% ----------------------------------------------------------
    % Plot
    % -----------------------------------------------------------

    plot( ...
        xFace, ...
        Cf, ...
        'Color',cases(c).color, ...
        'LineWidth',1.8, ...
        'DisplayName',cases(c).name);

end

%% ==============================================================
% ZERO LINE
% ==============================================================

yline( ...

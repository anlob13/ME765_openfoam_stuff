% ==============================================================

fprintf('\n');
fprintf('============================================\n');
fprintf('Separation / reattachment estimates\n');
fprintf('============================================\n');

for c = 1:length(cases)

    x = cases(c).x;
    Cf = cases(c).Cf;

    %% Find sign changes

    idx = find(Cf(1:end-1).*Cf(2:end) <= 0);

    fprintf('\n%s:\n',cases(c).name);

    if isempty(idx)

        fprintf('  No zero crossings detected.\n');

    else

        for j = 1:length(idx)

            i = idx(j);

            %% Linear interpolation

            xZero = ...
                x(i) ...
                - Cf(i)*(x(i+1)-x(i)) ...
                /(Cf(i+1)-Cf(i));

            fprintf( ...
                '  Cf = 0 at x/h = %.4f\n', ...
                xZero);

        end

    end

end

%% ==============================================================
% FUNCTION: READ WALL SHEAR STRESS
% ==============================================================

function [V, patch, text] = readWallShearStress(filename)

    %% ----------------------------------------------------------
    % Open file
    % ----------------------------------------------------------

    fid = fopen(filename,'r');

    if fid == -1

        error( ...
            'Could not open %s', ...
            filename);

    end

    text = fread(fid,'*char')';

    fclose(fid);

    %% ----------------------------------------------------------
    % Find internalField
    % ----------------------------------------------------------

    idx = strfind( ...
        text, ...
        'internalField');

    if isempty(idx)

        error( ...
            'Could not find internalField in %s', ...
            filename);

    end

    idx = idx(1);

    localText = text(idx:end);

    %% ----------------------------------------------------------
    % Find internal field
    % ----------------------------------------------------------

    token = 'nonuniform List<vector>';

    idx2 = strfind( ...
        localText, ...
        token);

    %% ----------------------------------------------------------
    % Case 1: uniform internal field
    %
    % wallShearStress is normally zero in the volume, with
    % actual values supplied on the boundary.
    % ----------------------------------------------------------

    if isempty(idx2)

        error( ...
            ['Could not find nonuniform internalField. ' ...
             'This reader expects the wallShearStress file ' ...
             'to contain nonuniform boundary values.']);

    end

    idx2 = idx + idx2(1) - 1;

    afterType = ...
        text(idx2 + length(token):end);

    %% ----------------------------------------------------------
    % Number of vectors
    % ----------------------------------------------------------

    countMatch = regexp( ...
        afterType, ...
        '^\s*(\d+)', ...
        'tokens', ...
        'once');

    if isempty(countMatch)

        error( ...
            'Could not determine vector count in %s', ...
            filename);

    end

    N = str2double( ...
        countMatch{1});

    %% ----------------------------------------------------------
    % Find list opening parenthesis
    % ----------------------------------------------------------

    pRel = strfind( ...
        afterType, ...
        '(');

    if isempty(pRel)

        error( ...
            'Could not find vector list in %s', ...
            filename);

    end

    p = ...
        idx2 + length(token) + pRel(1) - 1;

    dataText = text(p+1:end);

    %% ----------------------------------------------------------
    % Extract vectors
    % ----------------------------------------------------------

    expr = [ ...
        '\(\s*' ...
        '([-+0-9.eE]+)\s+' ...
        '([-+0-9.eE]+)\s+' ...
        '([-+0-9.eE]+)\s*\)' ];

    tokens = regexp( ...
        dataText, ...
        expr, ...
        'tokens');

    if length(tokens) < N

        error( ...
            'Expected %d vectors but found %d in %s', ...
            N,length(tokens),filename);

    end

    tokens = tokens(1:N);

    V = zeros(N,3);

    for i = 1:N

        V(i,1) = str2double(tokens{i}{1});
        V(i,2) = str2double(tokens{i}{2});
        V(i,3) = str2double(tokens{i}{3});

    end

    patch = [];

end

%% ==============================================================
% FUNCTION: EXACT PERIODIC HILL GEOMETRY
% ==============================================================

function yw = hillHeight(xh)

    %% Convert x/h -> original coordinate in mm

    x_mm = mod(xh,9.0)*28.0;

    %% Mirror second half

    if x_mm > 198.0

        xs = 252.0 - x_mm;

    else

        xs = x_mm;

    end

    %% Piecewise polynomial

    if xs >= 0 && xs < 9

        y_mm = min( ...
            28.0, ...
            28.0 ...
          + 0.000000000000E+00*xs ...
          + 6.775070969851E-03*xs.^2 ...
          - 2.124527775800E-03*xs.^3);

    elseif xs >= 9 && xs < 14

        y_mm = ...
            2.507355893131E+01 ...
          + 9.754803562315E-01*xs ...
          - 1.016116352781E-01*xs.^2 ...
          + 1.889794677828E-03*xs.^3;

    elseif xs >= 14 && xs < 20

        y_mm = ...
            2.579601052357E+01 ...
          + 8.206693007457E-01*xs ...
          - 9.055370274339E-02*xs.^2 ...
          + 1.626510569859E-03*xs.^3;

    elseif xs >= 20 && xs < 30

        y_mm = ...
            4.046435022819E+01 ...
          - 1.379581654948E+00*xs ...
          + 1.945884504128E-02*xs.^2 ...
          - 2.070318932190E-04*xs.^3;

    elseif xs >= 30 && xs < 40

        y_mm = ...
            1.792461334664E+01 ...
          + 8.743920332081E-01*xs ...
          - 5.567361123058E-02*xs.^2 ...
          + 6.277731764683E-04*xs.^3;

    elseif xs >= 40 && xs < 54

        y_mm = max( ...
            0.0, ...
            5.639011190988E+01 ...
          - 2.010520359035E+00*xs ...
          + 1.644919857549E-02*xs.^2 ...
          + 2.674976141766E-05*xs.^3);

    else

        y_mm = 0;

    end

    %% Normalize

    yw = y_mm/28.0;

end